#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# string.sh — String transformation utilities (Bash)
#
# Pure functions: no side effects, no global state.
# Each function prints the result to stdout.
# ---------------------------------------------------------------------------

# ---------------------------------------------------------------------------
# slugify
# ---------------------------------------------------------------------------
slugify() {
  local text="$1"
  echo "$text" \
    | tr '[:upper:]' '[:lower:]' \
    | sed 's/[^[:alnum:][:space:]-]//g' \
    | sed 's/[[:space:]-]\+/-/g' \
    | sed 's/^-//; s/-$//'
}

# ---------------------------------------------------------------------------
# trim
# ---------------------------------------------------------------------------
trim() {
  local text="$1"
  text="${text#"${text%%[![:space:]]*}"}"
  text="${text%"${text##*[![:space:]]}"}"
  echo "$text"
}

# ---------------------------------------------------------------------------
# lower / upper
# ---------------------------------------------------------------------------
lower() { echo "$1" | tr '[:upper:]' '[:lower:]'; }
upper() { echo "$1" | tr '[:lower:]' '[:upper:]'; }

# ---------------------------------------------------------------------------
# reverse_words
# ---------------------------------------------------------------------------
reverse_words() {
  local text="$1"
  local -a words
  read -ra words <<< "$text"
  for ((i = ${#words[@]} - 1; i >= 0; i--)); do
    echo -n "${words[i]}"
    [[ $i -gt 0 ]] && echo -n " "
  done
  echo
}

# ---------------------------------------------------------------------------
# repeat
# ---------------------------------------------------------------------------
repeat() {
  local char="$1" count="$2"
  printf "%*s" "$count" "" | tr ' ' "$char"
}
